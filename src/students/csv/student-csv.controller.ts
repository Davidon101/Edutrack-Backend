/**
 * @fileoverview Student CSV controller providing endpoints for downloading CSV templates,
 * uploading student CSVs for pre-import validation, and confirming batch imports.
 * @module students/csv/student-csv.controller
 */

import {
  Controller,
  Post,
  Get,
  Body,
  Res,
  UploadedFile,
  UseInterceptors,
  ParseFilePipe,
  MaxFileSizeValidator,
  FileTypeValidator,
} from '@nestjs/common';
import { FileInterceptor } from '@nestjs/platform-express';
import {
  ApiTags,
  ApiOperation,
  ApiResponse,
  ApiBearerAuth,
  ApiConsumes,
  ApiBody,
} from '@nestjs/swagger';
import { Response } from 'express';
import { Role } from '@prisma/client';
import { IsString } from 'class-validator';
import { ApiProperty } from '@nestjs/swagger';
import { StudentCsvService } from './student-csv.service';
import { Roles } from '../../common/decorators/roles.decorator';
import {
  CurrentUser,
  JwtPayload,
} from '../../common/decorators/current-user.decorator';

/**
 * DTO for confirming an in-memory student CSV preview batch.
 */
class ConfirmStudentCsvDto {
  /**
   * Preview token received from `/students/csv/upload`.
   * @example 'a1b2c3d4-e5f6-7890-abcd-ef1234567890'
   */
  @ApiProperty({
    description: 'Preview token received from /students/csv/upload endpoint',
    example: 'a1b2c3d4-e5f6-7890-abcd-ef1234567890',
  })
  @IsString()
  previewToken: string;
}

/**
 * Controller managing student CSV onboarding and batch imports.
 */
@ApiTags('Students — CSV Import')
@ApiBearerAuth()
@Roles(Role.ADMIN)
@Controller('students/csv')
export class StudentCsvController {
  /**
   * Initializes the StudentCsvController.
   *
   * @param studentCsvService - Service managing student CSV operations.
   */
  constructor(private readonly studentCsvService: StudentCsvService) {}

  /**
   * Downloads a blank student CSV template.
   *
   * Note: The `studentId` column is excluded as it is automatically generated by the backend.
   *
   * @param res - Express response object for streaming the file.
   */
  @Get('template')
  @ApiOperation({
    summary: 'Download blank student CSV template',
    description:
      'Provides a sample CSV template with columns: fullName, gender, dateOfBirth, className, admissionNumber. Note: studentId is omitted as it is auto-generated.',
  })
  @ApiResponse({
    status: 200,
    description: 'Student CSV template downloaded successfully.',
  })
  @ApiResponse({
    status: 401,
    description: 'Unauthorized. Missing or invalid bearer token.',
  })
  @ApiResponse({
    status: 403,
    description: 'Forbidden. Requires ADMIN role.',
  })
  downloadTemplate(@Res() res: Response) {
    const filePath = this.studentCsvService.getTemplatePath();
    res.download(filePath, 'student-template.csv');
  }

  /**
   * Uploads a student CSV file, parses rows, and returns a preview without saving to the database.
   *
   * @param file - Uploaded CSV file from multipart form data.
   * @param user - Authenticated user JWT payload.
   * @returns Preview token, validation counts, and parsed row status.
   */
  @Post('upload')
  @UseInterceptors(FileInterceptor('file'))
  @ApiConsumes('multipart/form-data')
  @ApiOperation({
    summary: 'Upload student CSV for preview',
    description:
      'Parses CSV rows, verifies unique admission numbers and valid classes, and returns a preview session token without writing to database.',
  })
  @ApiBody({
    schema: {
      type: 'object',
      properties: {
        file: {
          type: 'string',
          format: 'binary',
          description: 'CSV file (max 10MB)',
        },
      },
    },
  })
  @ApiResponse({
    status: 200,
    description: 'CSV uploaded and parsed into preview session.',
  })
  @ApiResponse({
    status: 400,
    description: 'Bad request. File missing or invalid format.',
  })
  @ApiResponse({
    status: 401,
    description: 'Unauthorized. Missing or invalid bearer token.',
  })
  @ApiResponse({
    status: 403,
    description: 'Forbidden. Requires ADMIN role.',
  })
  uploadCsv(
    @UploadedFile(
      new ParseFilePipe({
        validators: [
          new MaxFileSizeValidator({ maxSize: 10 * 1024 * 1024 }),
          new FileTypeValidator({ fileType: 'text/csv' }),
        ],
        fileIsRequired: true,
      }),
    )
    file: Express.Multer.File,
    @CurrentUser() user: JwtPayload,
  ) {
    return this.studentCsvService.uploadCsv(
      file.buffer,
      file.originalname,
      user.schoolId!,
      user.sub,
    );
  }

  /**
   * Confirms a preview session and creates all valid student records.
   *
   * @param dto - Preview token payload.
   * @param user - Authenticated user JWT payload.
   * @returns Import summary metrics.
   */
  @Post('confirm')
  @ApiOperation({
    summary: 'Confirm CSV preview',
    description:
      'Creates permanent student records and user credentials for all valid rows from the specified preview session.',
  })
  @ApiResponse({
    status: 200,
    description: 'Batch import completed.',
  })
  @ApiResponse({
    status: 400,
    description: 'Bad request. Invalid or expired preview token.',
  })
  @ApiResponse({
    status: 401,
    description: 'Unauthorized. Missing or invalid bearer token.',
  })
  @ApiResponse({
    status: 403,
    description: 'Forbidden. Requires ADMIN role.',
  })
  confirmCsv(
    @Body() dto: ConfirmStudentCsvDto,
    @CurrentUser() user: JwtPayload,
  ) {
    return this.studentCsvService.confirmCsv(
      dto.previewToken,
      user.schoolId!,
      user.sub,
    );
  }
}
